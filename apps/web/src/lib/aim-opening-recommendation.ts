/**
 * @description 构建爆款开头推荐 Prompt（用于生成高吸引力开头候选）
 * @param input - 包含用户指令、原开头片段和完整稿子的对象
 * @returns 用于 LLM 生成开头推荐的完整 Prompt
 */
export function buildOpeningRecommendationPrompt(input: {
  commandInput: string
  openingSegment: string
  fullText: string
}) {
  const sourceContext = input.fullText.slice(0, 3000)
  return [
    OPENING_RECOMMENDATION_INSTRUCTIONS,
    "",
    `用户要求：${input.commandInput}`,
    "",
    `原开头：\n${input.openingSegment}`,
    "",
    `完整稿子参考：\n${sourceContext}`,
  ].join("\n")
}
